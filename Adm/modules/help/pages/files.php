<h3>📁 Файловый менеджер</h3>

<p>Раздел для работы с файлами проекта прямо из админки.</p>

<h4>Возможности</h4>
<ul>
    <li>Просмотр всех файлов проекта</li>
    <li>Создание новых файлов и папок</li>
    <li>Переименование</li>
    <li>Удаление (с созданием <code>.bak</code>)</li>
    <li>Редактирование кода через Ace Editor</li>
</ul>

<h4>Редактор кода</h4>
<p>Поддерживает подсветку для:</p>
<ul>
    <li>PHP</li>
    <li>HTML</li>
    <li>CSS</li>
    <li>JavaScript</li>
    <li>JSON</li>
</ul>

<h4>Горячие клавиши</h4>
<ul>
    <li><strong>Ctrl + S</strong> — сохранить файл</li>
    <li><strong>Tab</strong> — отступ (4 пробела)</li>
</ul>

<div class="warning">
    ⚠️ <strong>Важно:</strong> перед сохранением создаётся резервная копия <code>.bak</code>.
</div>

<div class="note">
    💡 <strong>Совет:</strong> для крупных правок лучше использовать VS Code + SFTP. Файловый менеджер — для быстрых изменений.
</div>