<h3>🚀 Начало работы</h3>

<p>Добро пожаловать в систему управления сайтом <strong>ZoomCRM</strong>!</p>

<h4>Что такое CMS</h4>
<p>Это модульная система управления контентом. Каждая страница сайта — это отдельный модуль, лежащий в папке <code>/modules/</code>.</p>

<h4>Структура сайта</h4>
<pre>/modules/              ← Модули (страницы сайта)
/blocks/               ← Блоки (вставляются в модули)
/templates/modules/    ← Шаблоны для модулей
/assets/               ← Стили, скрипты, изображения
/Adm/                  ← Админ-панель
/base/                 ← Конфигурация
/core/                 ← Ядро системы</pre>

<h4>Первый вход</h4>
<ol>
    <li>Открой админку: <code>/Adm/</code></li>
    <li>Введи логин и пароль администратора</li>
    <li>Ты попадёшь на дашборд</li>
</ol>

<h4>Основные разделы админки</h4>
<ul>
    <li><strong>Дашборд</strong> — общая статистика</li>
    <li><strong>Пользователи</strong> — управление пользователями</li>
    <li><strong>Группы</strong> — управление группами доступа</li>
    <li><strong>Модули</strong> — управление страницами сайта</li>
    <li><strong>Блоки</strong> — управление блоками (вставляются в модули)</li>
    <li><strong>Меню</strong> — управление навигацией сайта</li>
    <li><strong>Настройки</strong> — глобальные настройки сайта</li>
    <li><strong>Помощь</strong> — этот раздел</li>
</ul>

<div class="note">
    💡 <strong>Совет:</strong> начинай работу с раздела «Настройки» — задай название сайта, описание, контакты.
</div>