<h3>⚙️ Настройки сайта</h3>

<p>Раздел настроек содержит 6 вкладок с глобальными параметрами сайта.</p>

<h4>📋 Основные</h4>
<ul>
    <li><strong>Название сайта</strong> — обязательно. Используется в шапке и в <code>&lt;title&gt;</code></li>
    <li><strong>Описание</strong> — используется как meta description по умолчанию</li>
    <li><strong>Ключевые слова</strong> — через запятую</li>
    <li><strong>Email сайта</strong> — для уведомлений</li>
    <li><strong>Язык</strong> — влияет на <code>&lt;html lang&gt;</code></li>
    <li><strong>Часовой пояс</strong> — для дат</li>
</ul>

<h4>🎨 Внешний вид</h4>
<ul>
    <li><strong>Текст логотипа</strong> — показывается в шапке</li>
    <li><strong>Акцентный цвет</strong> — влияет на кнопки и ссылки</li>
    <li><strong>Шаблон по умолчанию</strong> — для новых модулей</li>
</ul>

<h4>📞 Контакты</h4>
<p>Телефон, email, адрес, режим работы — отображаются в подвале сайта.</p>

<h4>🔗 Соцсети</h4>
<p>Ссылки на ВКонтакте, Telegram, WhatsApp, YouTube, Instagram — отображаются в подвале.</p>

<h4>🔍 SEO</h4>
<ul>
    <li><strong>Meta Title по умолчанию</strong> — если у модуля нет своего</li>
    <li><strong>Meta Description по умолчанию</strong> — если у модуля нет своего</li>
    <li><strong>Google Analytics ID</strong> — код аналитики</li>
    <li><strong>Яндекс.Метрика ID</strong> — код аналитики</li>
</ul>

<h4>⚙️ Система</h4>
<ul>
    <li><strong>Режим обслуживания</strong> — сайт показывает заглушку</li>
    <li><strong>Модуль для обслуживания</strong> — какой модуль показывать</li>
    <li><strong>Перегенерировать robots.txt</strong> — кнопка</li>
    <li><strong>Перегенерировать sitemap.xml</strong> — кнопка</li>
</ul>

<div class="note">
    💡 <strong>SEO работает так:</strong> сначала берётся SEO модуля, потом — глобальное SEO, потом — название и описание сайта.
</div>