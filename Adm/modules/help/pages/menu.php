<h3>📋 Меню</h3>

<p>Меню — это навигация сайта. Пункты могут вести на модули, внешние сайты, или быть группировками.</p>

<h4>Типы ссылок</h4>
<ul>
    <li><strong>📦 Модуль</strong> — выбор модуля из списка</li>
    <li><strong>🔗 Внешняя ссылка</strong> — URL любого сайта</li>
    <li><strong>📁 Без ссылки</strong> — только для группировки подпунктов</li>
</ul>

<h4>Создание пункта меню</h4>
<ol>
    <li>Админка → <strong>«Меню»</strong> → «Добавить пункт»</li>
    <li>Заполни: название, тип ссылки, ссылку</li>
    <li>Выбери родителя (если это подпункт)</li>
    <li>Настрой доступ для групп</li>
</ol>

<h4>Сортировка</h4>
<p>Перетаскивай пункты за иконку <strong>⠿</strong> (шесть точек) слева от названия. Порядок сохраняется автоматически.</p>

<h4>Вложенность</h4>
<p>Любой пункт может содержать подпункты. Для этого при создании выбери «Родительский пункт».</p>

<div class="note">
    💡 <strong>Правило:</strong> если пункт — родительский, он не должен вести на страницу. Используй тип «Без ссылки».
</div>