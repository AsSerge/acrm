<h3>👤 Пользователи и группы</h3>

<h4>Система ролей</h4>
<ul>
    <li><strong>Супер-админ</strong> — полный доступ (только 1 человек)</li>
    <li><strong>Администратор</strong> — всё, кроме управления пользователями и группами</li>
    <li><strong>Менеджер</strong> — контент (меню, модули, блоки)</li>
    <li><strong>Пользователь фронтенда</strong> — доступ к сайту по группам</li>
</ul>

<h4>Создание пользователя</h4>
<ol>
    <li>Раздел <strong>«Пользователи»</strong> → «Добавить пользователя»</li>
    <li>Заполни: имя, email, пароль, группу</li>
    <li>Сохрани</li>
</ol>

<h4>Создание группы</h4>
<ol>
    <li>Раздел <strong>«Группы»</strong> → «Добавить группу»</li>
    <li>Заполни: название, тип (admin / frontend)</li>
    <li>Сохрани</li>
</ol>

<h4>Права доступа к модулям</h4>
<p>У каждой группы есть уровни доступа к модулям:</p>
<ul>
    <li><code>none</code> — нет доступа</li>
    <li><code>view</code> — только просмотр</li>
    <li><code>edit</code> — просмотр и редактирование</li>
    <li><code>full</code> — полный доступ</li>
</ul>

<div class="warning">
    ⚠️ <strong>Важно:</strong> только Супер-админ может управлять пользователями и группами.
</div>